#!/usr/bin/env python3
"""Build Agent interview/review aids from their declared sources.

Default is a check. --apply updates only the three explicitly listed aids.
This detects source/render drift; it does not grade teaching quality.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MODULE = 'curriculum/09-agent'
QUESTIONS = MODULE + '/interview/questions.json'


def read(path: Path) -> str:
    return path.read_text(encoding='utf-8')


def build(root: Path = ROOT) -> dict[str, str]:
    docs = sorted((root / MODULE / 'docs').glob('[0-9][0-9]-*.md'))
    by_num = {int(p.name[:2]): p for p in docs}
    data = json.loads(read(root / QUESTIONS))
    items = data['questions']
    if [q['id'] for q in items] != list(range(1, 57)):
        raise ValueError('Interview training must preserve the reviewed 56-question set')
    if len({q['question'] for q in items}) != len(items):
        raise ValueError('Duplicate interview question')
    if len({q['answer'].strip() for q in items}) != len(items):
        raise ValueError('Duplicate full answers: inspect whether different questions were conflated')
    qa = ['# Agent｜高频面试题', '', '[← 模块入口](../README.md) · [综合复习](../review/README.md) · [易错点](面试易错点.md) · [速查](面试前速查表.md)', '',
          '本页是口述与追问训练，不代替正文。每道题链接到建立相关机制的位置；题目与答案直接显示，自测位于各章和 Review。真实来源与冻结频次见[Canonical](../../../interview/canonical/agent-harness.md)，本页不重新计算热度。', '',
          '<!-- generated by tools/sync_agent_materials.py; edit questions.json -->', '']
    for q in items:
        p = by_num[q['chapter']]
        if f'id="core-{q["section"]}"' not in read(p):
            raise ValueError(f'Question {q["id"]} points to a missing primary explanation')
        qa += [f'### {q["id"]}. {q["question"]}', '', q['answer'].strip(), '',
               f'[回看第{q["chapter"]}章的机制](../docs/{p.name}#core-{q["section"]})', '']
    mistakes = ['# Agent｜面试易错点', '', '[← 模块入口](../README.md) · [高频题](高频面试题.md) · [速查](面试前速查表.md)', '',
                '按正式章节回顾容易误解的边界。内容直接取自各章易错点，修改时以正文为准，不单独维护另一套规则。', '',
                '<!-- generated by tools/sync_agent_materials.py; edit chapter pitfalls -->', '']
    capability = ['# Agent｜能力与正式章节映射', '', '[← 资料索引](README.md) · [课程](../../curriculum/09-agent/README.md)', '',
                  '本页定位完整机制的主责位置，不另建学习路线。真人问题的教学映射与保留范围见[修订记录](../../guide/project/agent-clarity-refinement-2026-09-28.md)；不改变 Canonical 的题目归属或冻结统计。', '',
                  '<!-- generated by tools/sync_agent_materials.py -->', '', '| 章节 | 主责问题 |', '|---|---|']
    for n, p in by_num.items():
        text = read(p)
        title = next(line[2:] for line in text.splitlines() if line.startswith('# '))
        topic = re.sub(r'^\d+\.\s*', '', title)
        pit = text.split('## ⚠️ 易错点', 1)[1].split('## 本章自测', 1)[0]
        warnings = re.findall(r'^> ⚠️\s*(.+)$', pit, re.M)
        if not warnings:
            raise ValueError(f'{p.name}: missing pitfalls source')
        mistakes += [f'## {n:02d}｜[{topic}](../docs/{p.name})', '']
        mistakes += ['> ⚠️ ' + warning for warning in warnings]
        mistakes += ['']
        capability.append(f'| [{n:02d}](../../{MODULE}/docs/{p.name}) | {topic} |')
    return {
        MODULE + '/interview/高频面试题.md': '\n'.join(qa).rstrip() + '\n',
        MODULE + '/interview/面试易错点.md': '\n'.join(mistakes).rstrip() + '\n',
        'references/agent/runtime-capability-map.md': '\n'.join(capability).rstrip() + '\n',
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = []
    for path, text in build().items():
        target = ROOT / path
        if not target.exists() or read(target) != text:
            changed.append(path)
            if args.apply:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding='utf-8', newline='\n')
    print('Agent generated aids:', ', '.join(changed) if changed else 'in sync')
    return int(bool(changed) and not args.apply)


if __name__ == '__main__':
    raise SystemExit(main())
